@app.get("/boss", response_class=HTMLResponse)
async def boss_dashboard(request: Request):
    # Calculate stats
    total_revenue = sum(500 for j in JOBS_DB.values() if j.get("paid"))
    active_jobs = len([j for j in JOBS_DB.values() if not j.get("paid")])
    
    return templates.TemplateResponse(
        request=request, 
        name="boss.html", 
        context={
            "jobs": list(JOBS_DB.values()),
            "logs": CONSOLE_LOGS,
            "upi_id": UPI_VPA,
            "total_revenue": total_revenue,
            "active_jobs": active_jobs
        }
    )

@app.post("/boss/job/{job_id}/approve")
async def boss_approve_job(job_id: str):
    job = JOBS_DB.get(job_id)
    if job:
        job["paid"] = True
        job["status"] = "COMPLETED"
    return RedirectResponse(url="/boss", status_code=303)

