from google import genai

app = FastAPI(title="Two-Portal Autonomous AI Agency")

BASE_DIR = Path(__file__).resolve().parent
TEMPLATES_DIR = BASE_DIR / "templates"
templates = Jinja2Templates(directory=str(TEMPLATES_DIR))

# Credentials
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY", "").strip()
TELEGRAM_BOT_TOKEN = os.getenv("TELEGRAM_BOT_TOKEN", "").strip()
TELEGRAM_CHAT_ID = os.getenv("TELEGRAM_CHAT_ID", "").strip()
RENDER_EXTERNAL_URL = os.getenv("RENDER_EXTERNAL_URL", "").strip()
UPI_VPA = os.getenv("UPI_VPA", "yourvpa@upi").strip()

client = None
if GEMINI_API_KEY:
    try:
        client = genai.Client(api_key=GEMINI_API_KEY)
    except Exception:
        client = None

CONSOLE_LOGS: List[str] = [
    f"[{datetime.now().strftime('%H:%M:%S')}] Core Online. 3-Bot Mesh operational.",
    f"[{datetime.now().strftime('%H:%M:%S')}] Client storefront & Boss terminal linked."
]

def add_log(bot_name: str, msg: str):
    CONSOLE_LOGS.insert(0, f"[{datetime.now().strftime('%H:%M:%S')}] [{bot_name}] {msg}")
    if len(CONSOLE_LOGS) > 30:
        CONSOLE_LOGS.pop()

